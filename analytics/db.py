"""MotherDuck uploader for the Cricket Analytics pipeline.

This script copies the production tables (generated by Subtask 7) from the local
DuckDB file / Parquet exports to a MotherDuck cloud database.

Usage (run from project root):
    py -m analytics.db                 # upload all tables
    py -m analytics.db --verify        # upload then run a quick row‑count check

Prerequisites:
  • A MotherDuck token with read‑write privileges (see the .env.example file).
  • Packages `duckdb` and `python-dotenv` installed.

The script is deliberately tiny – it only opens a remote DuckDB connection via the
`md://` URI, creates/replaces the four production tables by reading the Parquet files
produced by Subtask 7, and optionally validates row counts.
"""

import os
import argparse
from pathlib import Path
import duckdb
from dotenv import load_dotenv

# ----------------------------------------------------------------------
# Resolve project root (two levels up from this file) and load the .env file
# ----------------------------------------------------------------------
PROJECT_ROOT = Path(__file__).resolve().parents[1]
ENV_PATH = PROJECT_ROOT / "analytics" / ".env"
load_dotenv(dotenv_path=ENV_PATH)

# ----------------------------------------------------------------------
# MotherDuck token – required for any remote operation
# ----------------------------------------------------------------------
MOTHERDUCK_TOKEN = os.getenv("MOTHERDUCK_TOKEN")
if not MOTHERDUCK_TOKEN:
    raise RuntimeError(
        "MOTHERDUCK_TOKEN not found. Create a token at https://motherduck.com and "
        f"add it to {ENV_PATH.as_posix()} (see .env.example)."
    )

# ----------------------------------------------------------------------
# Paths to the Parquet files generated by Subtask 7
# ----------------------------------------------------------------------
PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"
PARQUET_MAP = {
    "dim_matches": PROCESSED_DIR / "dim_matches.parquet",
    "dim_grounds": PROCESSED_DIR / "dim_grounds.parquet",
    "dim_players": PROCESSED_DIR / "dim_players.parquet",
    "fact_deliveries_master": PROCESSED_DIR / "fact_deliveries_master.parquet",
}

def _upload_table(parquet_path: Path, table_name: str, remote_con: duckdb.DuckDBPyConnection) -> None:
    """Replace `<table_name>` with the contents of `<parquet_path>` on MotherDuck.

    The `read_parquet` function streams the file directly into the remote
    DuckDB engine, which is efficient for large data sets.
    """
    if not parquet_path.exists():
        raise FileNotFoundError(f"Parquet file not found: {parquet_path}")
    remote_con.execute(
        f"""
        CREATE OR REPLACE TABLE {table_name} AS
        SELECT * FROM read_parquet('{parquet_path.as_posix()}');
        """
    )
    print(f"✅ Uploaded {parquet_path.name} → {table_name}")

def upload_all(verify: bool = False) -> None:
    """Upload every production table to MotherDuck.

    If `verify` is True, a quick row‑count QA is performed after the upload.
    """
    # Open a remote MotherDuck connection.
    # DuckDB automatically reads the MOTHERDUCK_TOKEN environment variable when you use "md:".
    # This avoids embedding the token directly in the URI (which caused the IO Error).
    os.environ["motherduck_token"] = MOTHERDUCK_TOKEN
    remote = duckdb.connect("md:")

    # Transfer each table.
    for tbl, pth in PARQUET_MAP.items():
        _upload_table(pth, tbl, remote)

    if verify:
        # Simple integrity check: row counts for each table.
        print("\n🔎 Remote QA – row counts")
        qa_df = remote.execute(
            """
            SELECT 'dim_matches' AS tbl, COUNT(*) AS rows FROM dim_matches UNION ALL
            SELECT 'dim_grounds' AS tbl, COUNT(*) AS rows FROM dim_grounds UNION ALL
            SELECT 'dim_players' AS tbl, COUNT(*) AS rows FROM dim_players UNION ALL
            SELECT 'fact_deliveries_master' AS tbl, COUNT(*) AS rows FROM fact_deliveries_master;
            """
        ).fetchdf()
        print(qa_df.to_string(index=False))

    remote.close()
    print("\n🚀 All tables are now live on MotherDuck!")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Upload DuckDB tables to MotherDuck")
    parser.add_argument(
        "--verify",
        action="store_true",
        help="Run a quick row‑count check after uploading",
    )
    args = parser.parse_args()
    upload_all(verify=args.verify)
